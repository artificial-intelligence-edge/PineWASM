use crate::command::{output, pinned_cargo, repo_root, sha256};
use crate::TaskResult;
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

const LICENSE_NAMES: [&str; 7] = [
    "license",
    "licence",
    "copying",
    "notice",
    "copyright",
    "thirdpartynotices",
    "third-party-notices",
];

#[derive(Default)]
pub(crate) struct LicenseText {
    pub(crate) text: String,
    pub(crate) uses: BTreeSet<String>,
}

/// One resolved production dependency: `name@version (license expression)`.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) struct InventoryPackage {
    pub(crate) name: String,
    pub(crate) version: String,
    pub(crate) expression: String,
}

impl InventoryPackage {
    pub(crate) fn label(&self) -> String {
        format!("{}@{} ({})", self.name, self.version, self.expression)
    }
}

/// The license texts of one resolved dependency graph, keyed by text digest.
pub(crate) struct Inventory {
    pub(crate) packages: Vec<InventoryPackage>,
    pub(crate) groups: BTreeMap<String, LicenseText>,
}

type SelectedPackages = BTreeMap<(String, String, String), Value>;

pub(crate) fn run(args: &[String]) -> TaskResult {
    let mut check = false;
    let mut selected_root = None;
    let mut index = 0;
    while index < args.len() {
        match args[index].as_str() {
            "--check" => check = true,
            "--repo" if index + 1 < args.len() => {
                selected_root = Some(PathBuf::from(&args[index + 1]));
                index += 1;
            }
            _ => return Err("usage: generate-licenses [--check] [--repo DIR]".into()),
        }
        index += 1;
    }
    let root = selected_root.map_or_else(repo_root, |path| {
        path.canonicalize()
            .map_err(|error| format!("cannot resolve {}: {error}", path.display()))
    })?;
    if !root.join("Cargo.toml").is_file()
        || !root
            .join("crates/pinewasm_aot/runtime/Cargo.toml")
            .is_file()
    {
        return Err(format!("not a PineWASM checkout: {}", root.display()));
    }
    let rendered = render(&root)?;
    let output_path = root.join("THIRD_PARTY_LICENSES.txt");
    if check {
        let current = fs::read_to_string(&output_path).unwrap_or_default();
        if current != rendered {
            return Err(
                "THIRD_PARTY_LICENSES.txt is stale; run `cargo xtask generate-licenses`".into(),
            );
        }
        println!("License bundle is current: THIRD_PARTY_LICENSES.txt");
    } else {
        fs::write(&output_path, rendered)
            .map_err(|error| format!("cannot write {}: {error}", output_path.display()))?;
        println!("Wrote THIRD_PARTY_LICENSES.txt");
    }
    Ok(())
}

fn render(root: &Path) -> TaskResult<String> {
    let mut groups: BTreeMap<String, LicenseText> = BTreeMap::new();
    let cargo_count = collect_cargo(root, &mut groups)?;
    let project_license = normalized_text(&root.join("LICENSE"))?;
    let notice = normalized_text(&root.join("NOTICE"))?;
    let mut parts = vec![
        "PINEWASM DISTRIBUTION LICENSES AND NOTICES".to_string(),
        "=".repeat(49),
        String::new(),
        "This file is generated by the Rust-native `pinewasm_xtask generate-licenses` command."
            .into(),
        "Do not edit it by hand.".into(),
        String::new(),
        "Source repository:".into(),
        env!("CARGO_PKG_REPOSITORY").into(),
        String::new(),
        "PineWASM is licensed under AGPL-3.0-only. The complete project".into(),
        "license follows.".into(),
        String::new(),
        project_license,
        String::new(),
        "PROJECT NOTICE".into(),
        "=".repeat(14),
        String::new(),
        notice,
        String::new(),
        "DEPENDENCY LICENSE TEXTS".into(),
        "=".repeat(24),
        String::new(),
        format!("Resolved inventory: {cargo_count} production Cargo packages."),
        "Identical license texts are printed once and list every package that uses them.".into(),
        String::new(),
    ];
    parts.extend(render_groups(groups));
    Ok(format!("{}\n", parts.join("\n").trim_end()))
}

/// Render every license-text group in the inventory's stable order: by the
/// first (lowercased) package label that uses the text, then by text digest.
pub(crate) fn render_groups(groups: BTreeMap<String, LicenseText>) -> Vec<String> {
    let mut ordered = groups.into_values().collect::<Vec<_>>();
    ordered.sort_by(|left, right| {
        left.uses
            .iter()
            .next()
            .map(|value| value.to_ascii_lowercase())
            .cmp(
                &right
                    .uses
                    .iter()
                    .next()
                    .map(|value| value.to_ascii_lowercase()),
            )
            .then_with(|| sha256(left.text.as_bytes()).cmp(&sha256(right.text.as_bytes())))
    });
    let mut parts = Vec::new();
    for (index, group) in ordered.into_iter().enumerate() {
        parts.push(format!("--- License text {} ---", index + 1));
        parts.push("Applies to:".into());
        parts.extend(group.uses.into_iter().map(|use_| format!("  - {use_}")));
        parts.push(String::new());
        parts.push(group.text);
        parts.push(String::new());
    }
    parts
}

/// The non-development dependency closure of the standalone AOT runtime
/// crate: the third-party code that can be spliced into an emitted artifact.
/// This is the same resolution `generate-licenses` performs for the runtime
/// graph, restricted to that graph, so the artifact bundle cannot disagree
/// with `THIRD_PARTY_LICENSES.txt`.
pub(crate) fn runtime_inventory(root: &Path) -> TaskResult<Inventory> {
    let selected = runtime_packages(root)?;
    let mut groups = BTreeMap::new();
    collect_license_texts(&selected, &mut groups)?;
    let packages = selected
        .iter()
        .map(|((name, version, _), package)| InventoryPackage {
            name: name.clone(),
            version: version.clone(),
            expression: package["license"]
                .as_str()
                .unwrap_or("license expression not declared")
                .to_string(),
        })
        .collect();
    Ok(Inventory { packages, groups })
}

fn collect_cargo(root: &Path, groups: &mut BTreeMap<String, LicenseText>) -> TaskResult<usize> {
    let mut selected = workspace_packages(root)?;
    selected.extend(runtime_packages(root)?);
    collect_license_texts(&selected, groups)?;
    Ok(selected.len())
}

/// Every external package reachable from a non-tooling workspace member
/// through a non-development edge.
fn workspace_packages(root: &Path) -> TaskResult<SelectedPackages> {
    let workspace = cargo_metadata(root, &root.join("Cargo.toml"), false)?;
    let packages = workspace["packages"]
        .as_array()
        .ok_or_else(|| "cargo metadata packages is not an array".to_string())?;
    let tool_ids = packages
        .iter()
        .filter(|package| package["name"].as_str() == Some("pinewasm_xtask"))
        .filter_map(|package| package["id"].as_str())
        .collect::<BTreeSet<_>>();
    let workspace_roots = workspace["workspace_members"]
        .as_array()
        .ok_or_else(|| "cargo metadata workspace_members is not an array".to_string())?
        .iter()
        .filter_map(Value::as_str)
        .filter(|id| !tool_ids.contains(id))
        .map(ToString::to_string)
        .collect::<Vec<_>>();
    reachable_external_packages(&workspace, &workspace_roots)
}

/// Every external package reachable from the standalone AOT runtime crate
/// with all features enabled, through a non-development edge.
fn runtime_packages(root: &Path) -> TaskResult<SelectedPackages> {
    let runtime = cargo_metadata(
        root,
        &root.join("crates/pinewasm_aot/runtime/Cargo.toml"),
        true,
    )?;
    let runtime_roots = runtime["packages"]
        .as_array()
        .ok_or_else(|| "runtime cargo metadata packages is not an array".to_string())?
        .iter()
        .filter(|package| {
            package["name"].as_str() == Some("pinewasm_aot_runtime") && package["source"].is_null()
        })
        .filter_map(|package| package["id"].as_str())
        .map(ToString::to_string)
        .collect::<Vec<_>>();
    if runtime_roots.len() != 1 {
        return Err("expected exactly one local Cargo package named pinewasm_aot_runtime".into());
    }
    reachable_external_packages(&runtime, &runtime_roots)
}

fn collect_license_texts(
    selected: &SelectedPackages,
    groups: &mut BTreeMap<String, LicenseText>,
) -> TaskResult {
    let mut missing = Vec::new();
    let mut apache_text = None;
    for ((name, version, _source), package) in selected {
        let manifest = package["manifest_path"]
            .as_str()
            .ok_or_else(|| format!("package {name} has no manifest path"))?;
        let directory = Path::new(manifest)
            .parent()
            .ok_or_else(|| format!("package {name} manifest has no parent"))?;
        let files = license_files(directory)?;
        let expression = package["license"]
            .as_str()
            .unwrap_or("license expression not declared");
        let label = format!("Cargo: {name}@{version} ({expression})");
        if files.is_empty() {
            missing.push((label, expression.to_string()));
            continue;
        }
        for license_path in files {
            let text = normalized_text(&license_path)?;
            if license_path
                .file_name()
                .and_then(|value| value.to_str())
                .is_some_and(|value| value.eq_ignore_ascii_case("license-apache"))
            {
                apache_text = Some(text.clone());
            }
            add_text(
                groups,
                text,
                format!(
                    "{label}; {}",
                    license_path
                        .file_name()
                        .unwrap_or_default()
                        .to_string_lossy()
                ),
            );
        }
    }
    let mut unresolved = Vec::new();
    for (label, expression) in missing {
        if expression.contains("Apache-2.0") {
            if let Some(text) = &apache_text {
                add_text(
                    groups,
                    text.clone(),
                    format!("{label}; selected Apache-2.0 text"),
                );
                continue;
            }
        }
        unresolved.push(label);
    }
    if !unresolved.is_empty() {
        return Err(format!(
            "Cargo packages without bundled license text:\n  {}",
            unresolved.join("\n  ")
        ));
    }
    Ok(())
}

fn cargo_metadata(root: &Path, manifest: &Path, all_features: bool) -> TaskResult<Value> {
    let mut command = pinned_cargo(root)?;
    command
        .current_dir(root)
        .args([
            "metadata",
            "--locked",
            "--format-version",
            "1",
            "--manifest-path",
        ])
        .arg(manifest);
    if all_features {
        command.arg("--all-features");
    }
    let result = output(&mut command)?;
    serde_json::from_slice(&result.stdout)
        .map_err(|error| format!("cannot parse cargo metadata: {error}"))
}

fn reachable_external_packages(metadata: &Value, roots: &[String]) -> TaskResult<SelectedPackages> {
    let packages = metadata["packages"]
        .as_array()
        .ok_or_else(|| "metadata packages missing".to_string())?;
    let nodes = metadata["resolve"]["nodes"]
        .as_array()
        .ok_or_else(|| "metadata resolve nodes missing".to_string())?;
    let packages_by_id = packages
        .iter()
        .filter_map(|package| Some((package["id"].as_str()?.to_string(), package)))
        .collect::<BTreeMap<_, _>>();
    let nodes_by_id = nodes
        .iter()
        .filter_map(|node| Some((node["id"].as_str()?.to_string(), node)))
        .collect::<BTreeMap<_, _>>();
    let mut reachable = BTreeSet::new();
    let mut pending = roots.to_vec();
    while let Some(id) = pending.pop() {
        if !reachable.insert(id.clone()) {
            continue;
        }
        let node = nodes_by_id
            .get(&id)
            .ok_or_else(|| format!("metadata node missing for {id}"))?;
        for dependency in node["deps"].as_array().into_iter().flatten() {
            let kinds = dependency["dep_kinds"].as_array();
            if kinds.is_some_and(|kinds| {
                !kinds.is_empty()
                    && kinds
                        .iter()
                        .all(|kind| kind["kind"].as_str() == Some("dev"))
            }) {
                continue;
            }
            if let Some(package) = dependency["pkg"].as_str() {
                pending.push(package.to_string());
            }
        }
    }
    let mut selected = BTreeMap::new();
    for id in reachable {
        let package = packages_by_id
            .get(&id)
            .ok_or_else(|| format!("metadata package missing for {id}"))?;
        let Some(source) = package["source"].as_str() else {
            continue;
        };
        let name = package["name"]
            .as_str()
            .ok_or_else(|| "package name missing".to_string())?;
        let version = package["version"]
            .as_str()
            .ok_or_else(|| "package version missing".to_string())?;
        selected.insert(
            (name.to_string(), version.to_string(), source.to_string()),
            (*package).clone(),
        );
    }
    Ok(selected)
}

fn license_files(directory: &Path) -> TaskResult<Vec<PathBuf>> {
    let mut files = Vec::new();
    for entry in fs::read_dir(directory)
        .map_err(|error| format!("cannot read {}: {error}", directory.display()))?
    {
        let path = entry
            .map_err(|error| format!("cannot read directory entry: {error}"))?
            .path();
        if !path.is_file() {
            continue;
        }
        let compact = path
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .to_ascii_lowercase()
            .replace(['_', ' '], "");
        if LICENSE_NAMES.iter().any(|name| {
            compact == *name
                || compact.starts_with(&format!("{name}."))
                || compact.starts_with(&format!("{name}-"))
        }) {
            files.push(path);
        }
    }
    files.sort_by_key(|path| {
        path.file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .to_ascii_lowercase()
    });
    Ok(files)
}

fn normalized_text(path: &Path) -> TaskResult<String> {
    let bytes =
        fs::read(path).map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    Ok(String::from_utf8_lossy(&bytes)
        .replace("\r\n", "\n")
        .replace('\r', "\n")
        .trim()
        .to_string())
}

fn add_text(groups: &mut BTreeMap<String, LicenseText>, text: String, use_: String) {
    let key = sha256(text.as_bytes());
    let group = groups.entry(key).or_insert_with(|| LicenseText {
        text,
        uses: BTreeSet::new(),
    });
    group.uses.insert(use_);
}
